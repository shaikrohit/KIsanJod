const LanguageContext = createContext<LanguageContextType>({
  locale: "en",
  setLocale: () => {},
  t: (key: string) => key,
});

export const LanguageProvider: React.FC<{ children: React.ReactNode }> = ({
  children,
}) => {
  const [locale, setLocaleState] = useState<Locale>("en");

  useEffect(() => {
    const saved = localStorage.getItem("kisanjod_locale") as Locale;
    if (saved && (saved === "en" || saved === "hi" || saved === "te")) {
      setLocaleState(saved);
    }
  }, []);

  const setLocale = (newLocale: Locale) => {
    setLocaleState(newLocale);
    try {
      localStorage.setItem("kisanjod_locale", newLocale);
    } catch {
      // Storage safety
    }
  };

  const t = (key: string): string => {
    return translations[locale]?.[key] || translations.en[key] || key;
  };

  return (
    <LanguageContext.Provider value={{ locale, setLocale, t }}>
      {children}
    </LanguageContext.Provider>
  );
};

export const useLanguage = () => useContext(LanguageContext);

export function getCropName(cropKey: string, locale: Locale): string {
  const c = (cropKey || "").toLowerCase();
  if (c.includes("wheat") || c.includes("gehun")) return locale === "te" ? "గోధుమలు" : locale === "hi" ? "गेहूं" : "Wheat";
  if (c.includes("paddy") || c.includes("dhan")) return locale === "te" ? "వరి" : locale === "hi" ? "धान" : "Paddy";
  if (c.includes("chana") || c.includes("gram")) return locale === "te" ? "శనగలు" : locale === "hi" ? "चना" : "Chana";
  if (c.includes("moong") || c.includes("mung")) return locale === "te" ? "పెసలు" : locale === "hi" ? "मूंग" : "Moong";
  if (c.includes("tomato")) return locale === "te" ? "టమాటా" : locale === "hi" ? "टमाटर" : "Tomato";
  if (c.includes("potato") || c.includes("aaloo")) return locale === "te" ? "బంగాళాదుంప" : locale === "hi" ? "आलू" : "Potato";
  if (c.includes("onion") || c.includes("pyaaz")) return locale === "te" ? "ఉల్లిపాయ" : locale === "hi" ? "प्याज" : "Onion";
  return cropKey;
}

